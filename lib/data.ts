/* The client's stock uses standard S–XXL apparel sizing. A product's `sizes`
   array lists the sizes stocked; any ladder size not present renders greyed /
   "Not available" on the detail page. Sarees are one-size (`freeSize`). */
export const SIZE_LADDER = ["S", "M", "L", "XL", "XXL"] as const;
export type Size = (typeof SIZE_LADDER)[number];

export type CatalogProduct = Product & {
  slug: string;
  code: string; // original Excel item name — kept so the backend can match rows
  images: string[]; // gallery — [0] is the primary/card image
  types: string[]; // filter tags, e.g. ["Kalamkari"] or ["Crop Tops"]
  sizes: Size[]; // sizes currently in stock (subset of SIZE_LADDER)
  freeSize?: boolean; // sarees & one-size items — no size selection
  stock: number; // units available (0 = out of stock)
  fabric: string;
  color: string;
  description: string;
  rating: number;
  reviews: number;
  categorySlug: string; // leaf shop slug for the breadcrumb (e.g. "sarees")
  mrp: number;
};

export const catalog: CatalogProduct[] = CATALOG;

export function getCatalogProduct(slug: string): CatalogProduct | undefined {
  return catalog.find((p) => p.slug === slug);
}

export function productsByCategory(category: string): CatalogProduct[] {
  return catalog.filter((p) => p.category === category);
}

