export function heroSlidesFor(slug: string): string[] {
  const slides = heroSlides[slug];
  if (slides && slides.length) return slides;
  const cfg = getShopCategory(slug);
  return cfg ? [cfg.image] : ["/images/hero.jpg"];
}

export function getShopCategory(slug: string): ShopCategory | undefined {
  return shopCategories.find((c) => c.slug === slug);
}

/* Products for a shop page — filtered by its display categories, keeping the
   catalog's authored order. */
export function productsForShop(slug: string): CatalogProduct[] {
  const cfg = getShopCategory(slug);
  if (!cfg) return [];
  // "New" lists only the tagged new-arrival items (the whole store lives under
  // /shop/all), preserving the NEW_ARRIVAL_SLUGS order.
  if (slug === "new") {
    return NEW_ARRIVAL_SLUGS.map((s) => getCatalogProduct(s)).filter(
      (p): p is CatalogProduct => Boolean(p),
    );
  }
  const set = new Set(cfg.categories);
  return catalog.filter((p) => set.has(p.category));
}

/* Filter type facets for a shop page (empty for combined pages → no Type filter). */
export function facetsForShop(slug: string): string[] {
  const cfg = getShopCategory(slug);
  if (!cfg?.facetKey) return [];
  return CATEGORY_FACETS[cfg.facetKey] ?? [];
}
